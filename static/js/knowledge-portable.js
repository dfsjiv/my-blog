(function () {
  'use strict';
  const FORMAT = 'zhen-article-backup';
  const TYPES = new Set(['article', 'solution', 'note', 'project', 'essay']);
  const APPEARANCES = new Set(['default', 'vinyl', 'collage', 'mecha', 'island', 'holo', 'spider', 'armor', 'hand']);
  const string = (value, length) => typeof value === 'string' ? value.slice(0, length) : '';
  function safeUrl(value) {
    if (!value) return '';
    try {
      const url = new URL(value, window.location.origin);
      return ['https:', 'http:'].includes(url.protocol) && !url.username && !url.password && url.href.length <= 2048 ? url.href : '';
    } catch { return ''; }
  }
  function filename(title, suffix) {
    const name = string(title, 80).normalize('NFKC').replace(/[<>:"/\\|?*\u0000-\u001f\u007f]/g, '-').replace(/[. ]+$/g, '').trim() || 'untitled';
    return (/^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)/i.test(name) ? 'article-' : '') + name + suffix;
  }
  function snapshot(post, maxContent = 2 * 1024 * 1024) {
    const content = typeof post.contentMarkdown === 'string' ? post.contentMarkdown : string(post.originalContent || post.content, maxContent + 1);
    if (content.length > maxContent) throw new Error('文章正文超过当前账号的大小限制。');
    const solution = post.solutionMeta || post.solution || {};
    return {
      title: string(post.title, 100), contentMarkdown: content,
      type: TYPES.has(post.type) ? post.type : 'article', category: string(post.category, 100),
      summary: string(post.summary, 500), slug: string(post.slug, 200),
      tags: (Array.isArray(post.tags) ? post.tags : []).slice(0, 30).map(tag => string(typeof tag === 'string' ? tag : tag?.name, 80)).filter(Boolean),
      appearance: APPEARANCES.has(post.appearance) ? post.appearance : 'default',
      coverUrl: safeUrl(post.coverUrl), sourceUrl: safeUrl(post.sourceUrl),
      solutionMeta: { platform: string(solution.platform, 80), problemId: string(solution.problemId, 100), problemTitle: string(solution.problemTitle, 200), problemUrl: safeUrl(solution.problemUrl), language: string(solution.language, 40) },
    };
  }
  function toMarkdown(post) {
    const value = snapshot(post);
    // JSON-quoted strings are valid YAML scalars, including embedded newlines.
    const metadata = [
      'title: ' + JSON.stringify(value.title), 'type: ' + JSON.stringify(value.type),
      'category: ' + JSON.stringify(value.category), 'tags: ' + JSON.stringify(value.tags),
      'summary: ' + JSON.stringify(value.summary), 'appearance: ' + JSON.stringify(value.appearance),
    ];
    if (value.coverUrl) metadata.push('cover: ' + JSON.stringify(value.coverUrl));
    if (value.sourceUrl) metadata.push('source: ' + JSON.stringify(value.sourceUrl));
    return '---\n' + metadata.join('\n') + '\n---\n\n' + value.contentMarkdown;
  }
  function toBackup(post) {
    return JSON.stringify({ format: FORMAT, version: 1, exportedAt: new Date().toISOString(), post: snapshot(post) }, null, 2);
  }
  function fromBackup(text, maxContent = 2 * 1024 * 1024) {
    if (typeof text !== 'string' || new TextEncoder().encode(text).length > Math.min(16 * 1024 * 1024, maxContent * 6 + 65536)) throw new Error('备份文件太大。');
    let value;
    try { value = JSON.parse(text); } catch { throw new Error('备份文件不是有效的 JSON。'); }
    if (value?.format !== FORMAT || value.version !== 1 || !value.post || typeof value.post !== 'object' || typeof value.post.contentMarkdown !== 'string') throw new Error('请选择本博客导出的文章备份。');
    // IDs, versions, owner IDs, credentials and publish/admin flags are never imported.
    return snapshot(value.post, maxContent);
  }
  function parseMarkdown(text) {
    const match = text.match(/^---\r?\n([\s\S]{0,16384}?)\r?\n---(?:\r?\n|$)/);
    if (!match) return { markdown: text };
    const values = {};
    const accepted = new Set(['title', 'type', 'category', 'tags', 'summary', 'appearance', 'cover', 'source']);
    for (const line of match[1].split(/\r?\n/)) {
      if (!line.trim() || /^\s*#/.test(line)) continue;
      const field = line.match(/^([a-z]+):\s*(.*)$/);
      // Only consume the explicit quoted format generated by this exporter.
      // General YAML/block syntax remains untouched rather than being guessed.
      if (!field || !accepted.has(field[1])) return { markdown: text };
      try { values[field[1]] = JSON.parse(field[2]); } catch { return { markdown: text }; }
    }
    if (typeof values.title !== 'string') return { markdown: text };
    const markdown = text.slice(match[0].length).replace(/^\r?\n/, '');
    const post = snapshot({ ...values, contentMarkdown: markdown, coverUrl: values.cover, sourceUrl: values.source });
    return { markdown, title: post.title, settings: { type: post.type, category: post.category, tags: post.tags.join(', '), summary: post.summary, appearance: post.appearance, coverUrl: post.coverUrl, sourceUrl: post.sourceUrl } };
  }
  function draftKey(ownerId, postId) {
    if (!Number.isSafeInteger(Number(ownerId)) || Number(ownerId) <= 0) throw new Error('请先登录后再使用写作备份。');
    return 'knowledge-writer-draft:v1:user:' + Number(ownerId) + ':' + (Number.isSafeInteger(Number(postId)) && Number(postId) > 0 ? 'post:' + Number(postId) : 'new');
  }
  function download(text, name, mime) {
    const url = URL.createObjectURL(new Blob([text], { type: mime + ';charset=utf-8' }));
    const link = document.createElement('a'); link.href = url; link.download = name;
    document.body.appendChild(link); link.click(); link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }
  function exportPost(post, kind = 'markdown') {
    const backup = kind === 'backup';
    download(backup ? toBackup(post) : toMarkdown(post), filename(post.title, backup ? '.article.json' : '.md'), backup ? 'application/json' : 'text/markdown');
  }
  window.KnowledgePortable = { snapshot, filename, toMarkdown, toBackup, fromBackup, parseMarkdown, draftKey, exportPost };
})();
